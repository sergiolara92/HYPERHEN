// A punctuation boundary is a conservative syntactic bound, never proof that
// the model's answer is semantically correct. No arbitrary word fragment is
// accepted. Numbers ending in '.', abbreviations, dotted identifiers, URLs and
// ellipses deliberately prefer no completion over a false completion.
inline Prefix complete_prefix(std::string_view raw, std::size_t maximum = kSpokenBytes,
                              unsigned maximum_sentences = kSpokenSentences) {
  Prefix result;
  if (!maximum || maximum > kSpokenBytes || !maximum_sentences ||
      maximum_sentences > kSpokenSentences) return result;
  std::vector<detail::Unit> units;
  if (!detail::decode(raw, units, result.incomplete_utf8_tail)) {
    result.utf8_valid = false;
    return result;
  }
  std::size_t first = 0;
  while (first < units.size() && detail::space(units[first].value)) ++first;
  if (first == units.size()) return result;
  bool content = false;
  for (std::size_t i = first; i < units.size(); ++i) {
    const auto c = units[i].value;
    if (units[i].end > maximum) break;
    if (!detail::terminal(c)) {
      if (detail::content_codepoint(c)) content = true;
      continue;
    }
    if (!content) continue;
    const auto token = detail::token_before(raw, units, i);
    if (token.find("://") != std::string::npos || token.compare(0, 4, "www.") == 0 ||
        token.find('/') != std::string::npos || token.find('\\') != std::string::npos) continue;
    if (c == '.') {
      if ((i && (detail::digit(units[i-1].value) || units[i-1].value == '.')) ||
          (i+1 < units.size() && (detail::digit(units[i+1].value) || units[i+1].value == '.')) ||
          detail::abbreviation(token)) continue;
    }
    std::size_t last = i;
    while (last+1 < units.size() && detail::terminal(units[last+1].value) &&
           units[last+1].value != '.') ++last;
    while (last+1 < units.size() && detail::closer(units[last+1].value)) ++last;
    if (units[last].end > maximum) continue;
    if (!detail::independent_terminal(c) && last+1 < units.size() &&
        !detail::space(units[last+1].value)) continue;
    result.source_bytes = units[last].end;
    result.text.assign(raw.substr(units[first].begin, result.source_bytes-units[first].begin));
    ++result.sentences;
    content = false;
    i = last;
    if (result.sentences >= maximum_sentences) break;
  }
  return result;
}

enum class FinishReason { none, sentence_goal, byte_limit, soft_decode_budget };
struct Decision {
  Prefix prefix;
  FinishReason reason = FinishReason::none;
  bool byte_limit_reached = false;
  bool finish() const { return reason != FinishReason::none && !prefix.text.empty(); }
};
inline Decision evaluate(std::string_view raw, std::uint64_t decode_elapsed_ms) {
  Decision result{complete_prefix(raw)};
  result.byte_limit_reached = raw.size() >= kSpokenBytes;
  if (!result.prefix.utf8_valid || result.prefix.text.empty()) return result;
  if (result.prefix.sentences >= kSpokenSentences) result.reason = FinishReason::sentence_goal;
  else if (result.byte_limit_reached) result.reason = FinishReason::byte_limit;
  else if (decode_elapsed_ms >= kSoftDecodeMs) result.reason = FinishReason::soft_decode_budget;
  return result;
}

struct RecoveryState {
  bool inference_timeout = false;
  bool cancelled = false;
  bool io_error = false;
  bool model_error = false;
  bool inference_error = false;
};
inline bool may_recover_timeout(RecoveryState state) {
  return state.inference_timeout && !state.cancelled && !state.io_error &&
      !state.model_error && !state.inference_error;
}
inline Prefix recover_timeout(std::string_view raw, RecoveryState state) {
  return may_recover_timeout(state) ? complete_prefix(raw) : Prefix{};
}
