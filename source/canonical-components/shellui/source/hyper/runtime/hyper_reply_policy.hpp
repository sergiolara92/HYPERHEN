struct Unit { std::uint32_t value; std::size_t begin, end; };
inline bool space(std::uint32_t c) {
  return c == ' ' || c == '\t' || c == '\r' || c == '\n' || c == 0x00a0 ||
      c == 0x1680 || (c >= 0x2000 && c <= 0x200a) || c == 0x2028 ||
      c == 0x2029 || c == 0x202f || c == 0x205f || c == 0x3000;
}
inline bool digit(std::uint32_t c) {
  return (c >= '0' && c <= '9') || (c >= 0x0660 && c <= 0x0669) ||
      (c >= 0x06f0 && c <= 0x06f9) || (c >= 0xff10 && c <= 0xff19);
}
inline bool closer(std::uint32_t c) {
  return c == '"' || c == '\'' || c == ')' || c == ']' || c == '}' ||
      c == 0x00bb || c == 0x2019 || c == 0x201d || c == 0x203a ||
      c == 0x3009 || c == 0x300b || c == 0x300d || c == 0x300f ||
      c == 0x3011 || c == 0xff09;
}
inline bool terminal(std::uint32_t c) {
  return c == '.' || c == '?' || c == '!' || c == 0x3002 ||
      c == 0xff01 || c == 0xff1f || c == 0x061f || c == 0x06d4 ||
      c == 0x0964 || c == 0x0965;
}
inline bool independent_terminal(std::uint32_t c) {
  return c != '.' && c != '?' && c != '!';
}
