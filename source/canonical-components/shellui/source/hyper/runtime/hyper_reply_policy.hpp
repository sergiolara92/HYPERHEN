inline bool decode(std::string_view raw, std::vector<Unit> &units, bool &tail) {
  tail = false;
  if (raw.size() > 8192) return false;
  for (std::size_t at = 0; at < raw.size();) {
    const auto start = at;
    const auto first = static_cast<unsigned char>(raw[at++]);
    std::uint32_t value = first, minimum = 0;
    unsigned continuation = 0;
    if (first < 0x80) {
      if (!first || first == 0x7f || (first < 0x20 && !space(first))) return false;
    } else if (first >= 0xc2 && first <= 0xdf) {
      continuation = 1; value = first & 0x1fu; minimum = 0x80;
    } else if (first >= 0xe0 && first <= 0xef) {
      continuation = 2; value = first & 0x0fu; minimum = 0x800;
    } else if (first >= 0xf0 && first <= 0xf4) {
      continuation = 3; value = first & 0x07u; minimum = 0x10000;
    } else return false;
    if (continuation > raw.size() - at) {
      // A token may end midway through a valid UTF8 codepoint. Validate the
      // bytes that are present before retaining an earlier complete sentence.
      for (std::size_t n = at; n < raw.size(); ++n)
        if ((static_cast<unsigned char>(raw[n]) & 0xc0u) != 0x80u) return false;
      if (at < raw.size()) {
        const auto second = static_cast<unsigned char>(raw[at]);
        if ((first == 0xe0 && second < 0xa0) || (first == 0xed && second >= 0xa0) ||
            (first == 0xf0 && second < 0x90) || (first == 0xf4 && second >= 0x90)) return false;
      }
      tail = true;
      break;
    }
    for (unsigned n = 0; n < continuation; ++n) {
      const auto next = static_cast<unsigned char>(raw[at++]);
      if ((next & 0xc0u) != 0x80u) return false;
      value = (value << 6u) | (next & 0x3fu);
    }
    if (value < minimum || value > 0x10ffff || (value >= 0xd800 && value <= 0xdfff)) return false;
    units.push_back({value, start, at});
  }
  return true;
}
inline std::string token_before(std::string_view raw, const std::vector<Unit> &u,
                                std::size_t index) {
  auto first = index;
  while (first && !space(u[first - 1].value)) --first;
  while (first < index && (u[first].value == '(' || u[first].value == '[' ||
      u[first].value == '{' || u[first].value == '"' || u[first].value == '\'' ||
      u[first].value == 0x00ab || u[first].value == 0x201c)) ++first;
  std::string result(raw.substr(u[first].begin, u[index].begin - u[first].begin));
  for (char &c : result) if (c >= 'A' && c <= 'Z') c = static_cast<char>(c + 'a' - 'A');
  return result;
}
inline bool abbreviation(std::string_view token) {
  if (token.empty() || token.find('.') != std::string_view::npos) return true;
  if (token.size() == 1 && ((token[0] >= 'a' && token[0] <= 'z') || digit(token[0]))) return true;
  constexpr std::string_view known[] = {"sig","sigra","sign","dott","dottssa","dr","dra",
      "prof","profssa","ecc","es","pag","pagg","art","cap","num","n",
      "mr","mrs","ms","jr","sr","st","vs","etc","inc","ltd","no","fig",
      "mme","mlle","pr","env","vol","av","apr","janv","févr",
      "hr","fr","nr","bzw","usw","vgl","ca","str","abs","sra","srta",
      "ud","uds","aprox","pág","págs","p.ex","p.ej"};
  for (const auto &word : known) if (token == word) return true;
  return false;
}
